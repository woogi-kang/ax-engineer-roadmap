import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const casesRoot = path.join(root, "case-studies");
const outputPath = path.join(root, "site", "app", "case-metadata.generated.ts");

const directories = fs
  .readdirSync(casesRoot, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && entry.name !== "_schema")
  .map((entry) => entry.name)
  .sort();

const metadata = Object.fromEntries(
  directories.map((directory) => {
    const caseFile = path.join(casesRoot, directory, "case.json");
    const item = JSON.parse(fs.readFileSync(caseFile, "utf8"));
    return [
      item.id,
      {
        title: item.title,
        industry: item.industry,
        difficulty: item.difficulty,
        risk: item.risk,
        evidenceStage: item.evidence_stage,
        readiness: item.readiness,
        recommendedAfter: item.recommended_after,
        learningOrder: item.learning_order,
        currentWriteImpact: item.current_write_impact,
        designedWriteImpact: item.designed_write_impact,
        currentAutonomy: item.current_autonomy,
        designedAutonomy: item.designed_autonomy,
        implementedProjectStages: item.implemented_project_stages,
        designedProjectStages: item.designed_project_stages,
      },
    ];
  }),
);

const counts = {
  total: directories.length,
  publicSimulation: Object.values(metadata).filter(
    (item) => item.evidenceStage === "public-simulation",
  ).length,
  simulationDesign: Object.values(metadata).filter(
    (item) => item.evidenceStage === "simulation-design",
  ).length,
};

const generated = `// Generated by scripts/generate-case-site-data.mjs. Do not edit by hand.\n\nexport const caseMetadata = ${JSON.stringify(metadata, null, 2)} as const;\n\nexport const generatedCaseCounts = ${JSON.stringify(counts, null, 2)} as const;\n`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(outputPath)
    ? fs.readFileSync(outputPath, "utf8")
    : "";
  if (current !== generated) {
    console.error(
      "사례 사이트 데이터가 case.json과 다릅니다. npm run generate:cases를 실행하세요.",
    );
    process.exit(1);
  }
  console.log(`사례 사이트 데이터 동기화 통과: ${counts.total}개`);
} else {
  fs.writeFileSync(outputPath, generated);
  console.log(`사례 사이트 데이터 생성: ${counts.total}개`);
}
